// Package secretbox implements port.SecretBox with AES-256-GCM envelope
// encryption: each value gets a fresh random data key, the data key is
// wrapped by the server's master key, and both layers authenticate the
// caller's aad. Rotating the master key means re-wrapping 48-byte data
// keys, never re-encrypting values; the leading version byte leaves room
// for a key id when that is needed.
package secretbox

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"encoding/base64"
	"errors"
	"fmt"
	"strings"

	"github.com/CaioAP/shinrin/backend/internal/port"
)

const (
	version  = 1
	keySize  = 32
	nonceLen = 12
	tagLen   = 16
	// wrappedLen is a data key sealed by the master key.
	wrappedLen = nonceLen + keySize + tagLen
)

// ErrOpen is returned for a value that was tampered with, sealed under
// another master key, or bound to other aad.
var ErrOpen = errors.New("secretbox: cannot open sealed value")

// Box seals and opens values with one master key.
type Box struct {
	master cipher.AEAD
}

var _ port.SecretBox = (*Box)(nil)

// ParseKey decodes a base64 (standard or URL alphabet) 32-byte master key,
// as generated by `openssl rand -base64 32`.
func ParseKey(s string) ([]byte, error) {
	s = strings.TrimSpace(s)
	for _, enc := range []*base64.Encoding{base64.StdEncoding, base64.URLEncoding, base64.RawStdEncoding, base64.RawURLEncoding} {
		if k, err := enc.DecodeString(s); err == nil {
			if len(k) != keySize {
				return nil, fmt.Errorf("secretbox: master key must be %d bytes, got %d", keySize, len(k))
			}
			return k, nil
		}
	}
	return nil, errors.New("secretbox: master key is not base64")
}

// New builds a Box from a 32-byte master key.
func New(masterKey []byte) (*Box, error) {
	if len(masterKey) != keySize {
		return nil, fmt.Errorf("secretbox: master key must be %d bytes", keySize)
	}
	a, err := newGCM(masterKey)
	if err != nil {
		return nil, err
	}
	return &Box{master: a}, nil
}

func newGCM(key []byte) (cipher.AEAD, error) {
	b, err := aes.NewCipher(key)
	if err != nil {
		return nil, err
	}
	return cipher.NewGCM(b)
}

// Seal implements port.SecretBox. Layout:
// version | nonce | wrapped data key | nonce | ciphertext.
func (b *Box) Seal(plaintext, aad []byte) ([]byte, error) {
	dek := make([]byte, keySize)
	if _, err := rand.Read(dek); err != nil {
		return nil, err
	}
	defer clear(dek)
	data, err := newGCM(dek)
	if err != nil {
		return nil, err
	}
	out := make([]byte, 1, 1+wrappedLen+nonceLen+len(plaintext)+tagLen)
	out[0] = version
	out, err = sealInto(b.master, out, dek, aad)
	if err != nil {
		return nil, err
	}
	return sealInto(data, out, plaintext, aad)
}

func sealInto(a cipher.AEAD, dst, plaintext, aad []byte) ([]byte, error) {
	nonce := make([]byte, nonceLen)
	if _, err := rand.Read(nonce); err != nil {
		return nil, err
	}
	dst = append(dst, nonce...)
	return a.Seal(dst, nonce, plaintext, aad), nil
}

// Open implements port.SecretBox.
func (b *Box) Open(sealed, aad []byte) ([]byte, error) {
	if len(sealed) < 1+wrappedLen+nonceLen+tagLen || sealed[0] != version {
		return nil, ErrOpen
	}
	w := sealed[1 : 1+wrappedLen]
	dek, err := b.master.Open(nil, w[:nonceLen], w[nonceLen:], aad)
	if err != nil {
		return nil, ErrOpen
	}
	defer clear(dek)
	data, err := newGCM(dek)
	if err != nil {
		return nil, err
	}
	rest := sealed[1+wrappedLen:]
	plain, err := data.Open(nil, rest[:nonceLen], rest[nonceLen:], aad)
	if err != nil {
		return nil, ErrOpen
	}
	return plain, nil
}
